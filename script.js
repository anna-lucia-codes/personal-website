function initImageClickToOpen() {
  const modal = document.createElement('div');
  modal.id = 'img-modal';
  modal.innerHTML = '<button id="img-modal-close" aria-label="Close">✕</button><img id="img-modal-img" alt="" />';
  document.body.appendChild(modal);

  const modalImg = modal.querySelector('#img-modal-img');

  function openModal(src) {
    modalImg.src = src;
    modal.classList.add('open');
    document.body.style.overflow = 'hidden';
  }

  function closeModal() {
    modal.classList.remove('open');
    document.body.style.overflow = '';
    modalImg.src = '';
  }

  modal.addEventListener('click', e => { if (e.target === modal) closeModal(); });
  modal.querySelector('#img-modal-close').addEventListener('click', closeModal);
  document.addEventListener('keydown', e => { if (e.key === 'Escape') closeModal(); });

  document.querySelectorAll('.image-grid img, .single-image img').forEach(img => {
    img.style.cursor = 'pointer';
    img.addEventListener('click', function() {
      const src = this.getAttribute('src');
      if (src) openModal(src);
    });
  });
}

document.addEventListener('DOMContentLoaded', () => {
  initNav();
  initRandomizer();
  initGridView();
  initActiveNavItem();
  initImageLazyLoading();
  initImageClickToOpen();
});
