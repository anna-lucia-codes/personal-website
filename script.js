function shuffleArrayInPlace(array) {
  for (let i = array.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [array[i], array[j]] = [array[j], array[i]];
  }
  return array;
}

function preloadImage(src) {
  return new Promise(resolve => {
    const img = new Image();
    img.onload = resolve;
    img.onerror = resolve;
    img.src = src;
  });
}

function showProject(item) {
  const linkEl  = document.getElementById('featured-link');
  const imgEl   = document.getElementById('featured-image');
  const titleEl = document.getElementById('card-title');
  const yearEl  = document.getElementById('card-year');
  const descEl  = document.getElementById('card-desc');

  if (!linkEl || !imgEl) return;

  const meta = projectMeta[item.href] || {};
  linkEl.href = item.href;
  imgEl.src   = item.image;
  if (titleEl) titleEl.textContent = meta.title || '';
  if (yearEl)  yearEl.textContent  = meta.year  || '';
  if (descEl)  descEl.textContent  = meta.desc  || '';
}

function revealCard(cardEl) {
  cardEl.style.transition = 'opacity 250ms ease, transform 250ms ease';
  cardEl.classList.remove('card-hidden');
  cardEl.addEventListener('transitionend', () => {
    cardEl.style.transition = '';
  }, { once: true });
}

function initRandomizer() {
  const button = document.getElementById('randomize-btn');
  const cardEl = document.getElementById('project-card');
  if (!button) return;

  let order = shuffleArrayInPlace(projects.slice());
  let currentItem = order[0];

  if (cardEl) {
    cardEl.classList.add('card-hidden');
    showProject(currentItem);
    preloadImage(currentItem.image).then(() => revealCard(cardEl));
  } else {
    showProject(currentItem);
  }

  button.addEventListener('click', () => {
    const newOrder = shuffleArrayInPlace(projects.slice());
    const idx = newOrder.indexOf(currentItem);
    if (idx !== -1) newOrder.splice(idx, 1);
    const nextItem = newOrder[0] || currentItem;

    if (!cardEl) {
      currentItem = nextItem;
      showProject(currentItem);
      return;
    }

    cardEl.classList.add('card-hidden');

    Promise.all([
      preloadImage(nextItem.image),
      new Promise(resolve => setTimeout(resolve, 260)),
    ]).then(() => {
      currentItem = nextItem;
      showProject(currentItem);
      revealCard(cardEl);
    });
  });
}

function initGridView() {
  const gridContainer = document.getElementById('projects-grid');
  if (!gridContainer) return;

  const uniqueProjects = [
    { image: 'images/structured/structure-06.png', href: 'emailart.html' },
    { image: 'images/structured/structure-02.jpg', href: 'oefenstof.html' },
    { image: 'images/structured/structure-07.png', href: 'thread.html' },
    { image: 'images/structured/structure-08.jpg', href: 'synths.html' },
    { image: 'images/structured/structure-03.jpg', href: 'yesyesno.html' },
    { image: 'images/structured/structure-04.png', href: '33million.html' },
    { image: 'images/structured/structure-09.jpg', href: 'generations.html' },
    { image: 'images/structured/structure-10.png', href: 'patchedparadise.html' },
    { image: 'images/structured/structure-12.jpg', href: 'AFWIPS.html' },
    { image: 'images/structured/structure-11.jpg', href: 'perpetual.html' },
    { image: 'images/structured/structure-05.png', href: 'loom.html' },
  ];

  const cards = uniqueProjects.map(project => {
    const meta = projectMeta[project.href] || {};

    const link = document.createElement('a');
    link.href = project.href;
    link.className = 'grid-card';
    link.setAttribute('aria-label', 'Open project');

    const imageBox = document.createElement('div');
    imageBox.className = 'card-image-box';

    const img = document.createElement('img');
    img.dataset.src = project.image;
    img.alt = meta.title || '';
    img.style.opacity = '0';
    img.style.width = '100%';
    img.style.height = '100%';
    img.style.objectFit = 'contain';
    img.style.display = 'block';

    imageBox.appendChild(img);

    const cardMeta = document.createElement('div');
    cardMeta.className = 'card-meta';

    const titleRow = document.createElement('div');
    titleRow.className = 'card-title-row';

    const title = document.createElement('span');
    title.className = 'card-title';
    title.textContent = meta.title || '';

    const year = document.createElement('span');
    year.className = 'card-year';
    year.textContent = meta.year || '';

    titleRow.appendChild(title);
    titleRow.appendChild(year);

    const rule = document.createElement('hr');
    rule.className = 'card-rule';

    const desc = document.createElement('p');
    desc.className = 'card-desc';
    desc.textContent = meta.desc || '';

    cardMeta.appendChild(titleRow);

    if (meta.tags && meta.tags.length) {
      const tagsEl = document.createElement('div');
      tagsEl.className = 'card-tags';
      meta.tags.forEach(tag => {
        const tagEl = document.createElement('span');
        tagEl.className = 'card-tag';
        tagEl.textContent = tag;
        tagsEl.appendChild(tagEl);
      });
      cardMeta.appendChild(tagsEl);
    }

    cardMeta.appendChild(rule);
    cardMeta.appendChild(desc);

    link.appendChild(imageBox);
    link.appendChild(cardMeta);

    return { link, img };
  });

  cards.forEach(({ link }) => gridContainer.appendChild(link));

  const imageObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const img = entry.target;
        if (img.dataset.src) {
          img.src = img.dataset.src;
          delete img.dataset.src;
          img.addEventListener('load', () => { img.style.opacity = '1'; }, { once: true });
          imageObserver.unobserve(img);
        }
      }
    });
  }, { rootMargin: '50px' });

  cards.forEach(({ img }) => imageObserver.observe(img));

  cards.slice(0, 4).forEach(({ img }) => {
    if (img.dataset.src) {
      img.src = img.dataset.src;
      delete img.dataset.src;
      img.addEventListener('load', () => { img.style.opacity = '1'; }, { once: true });
    }
  });
}

function initActiveNavItem() {
  const filename = window.location.pathname.split('/').pop() || '';
  document.querySelectorAll('.nav-link').forEach(link => link.classList.remove('active'));
  
  if (filename === 'more.html') {
    document.getElementById('nav-about')?.classList.add('active');
  } else if (filename === 'selected.html') {
    document.getElementById('nav-structure')?.classList.add('active');
  }
}

function toggleNavMenu() {
  const navMenu = document.getElementById('nav-menu');
  navMenu?.classList.toggle('open');
  document.body.classList.toggle('menu-open', navMenu?.classList.contains('open'));
  document.querySelector('.nav-toggle')?.classList.toggle('menu-open', navMenu?.classList.contains('open'));
}

function closeNavMenu() {
  document.getElementById('nav-menu')?.classList.remove('open');
  document.body.classList.remove('menu-open');
  document.querySelector('.nav-toggle')?.classList.remove('menu-open');
}

function initImageLazyLoading() {
  const images = document.querySelectorAll('.image-grid img, .single-image img');
  images.forEach(img => img.loading = 'lazy');
  
  const imageObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const img = entry.target;
        const handleLoad = () => {
          img.classList.add('loaded');
          img.style.opacity = '1';
        };
        if (img.complete && img.naturalHeight !== 0) {
          handleLoad();
        } else {
          img.addEventListener('load', handleLoad, { once: true });
        }
        imageObserver.unobserve(img);
      }
    });
  }, { rootMargin: '100px' });
  
  images.forEach(img => {
    img.style.opacity = '0';
    imageObserver.observe(img);
  });
  
  Array.from(images).slice(0, 4).forEach(img => {
    img.loading = 'eager';
    if (img.complete && img.naturalHeight !== 0) {
      img.classList.add('loaded');
      img.style.opacity = '1';
    } else {
      img.addEventListener('load', () => {
        img.classList.add('loaded');
        img.style.opacity = '1';
      }, { once: true });
    }
  });
}

